importScripts('config.js'); // generated by scripts/build.js
const API = CONFIG.API_URL, H = CONFIG.API_KEY ? { 'X-API-Key': CONFIG.API_KEY } : {};
chrome.sidePanel.setPanelBehavior({ openPanelOnActionClick: true });

const enc = blob => new Promise(r => { const f = new FileReader(); f.onload = () => r(f.result.split(',')[1]); f.readAsDataURL(blob); });
const grab = async url => {
  let u = url;
  try {
    const parsed = new URL(url);
    const wrapped = ['file', 'src', 'url'].map(k => parsed.searchParams.get(k)).find(Boolean);
    if (wrapped) u = new URL(wrapped, url).href;
  } catch {}
  const r = await fetch(u, { credentials: 'include' });
  if (!r.ok) throw new Error(`Document request failed (${r.status})`);
  const blob = await r.blob();
  const x = await enc(blob);
  const mime = x.startsWith('JVBER') ? 'application/pdf' : x.startsWith('/9j/') ? 'image/jpeg' : '';
  if (!mime) throw new Error(`Opened tab did not return a PDF or JPG (content type: ${blob.type || 'unknown'})`);
  return { b64: x, mime };
};

let watch = null;
chrome.tabs.onCreated.addListener(t => {
  if (!watch || t.openerTabId !== watch) return;
  const op = watch, id = t.id;
  const h = (i, c, tab) => {
    if (i !== id || c.status !== 'complete' || !tab.url || tab.url === 'about:blank') return;
    chrome.tabs.onUpdated.removeListener(h);
    grab(tab.url)
      .then(file => chrome.tabs.sendMessage(op, { t: 'pdf', url: tab.url, ...file }))
      .catch(e => chrome.tabs.sendMessage(op, { t: 'pdf', url: tab.url, error: String(e) }).catch(() => {}))
      .finally(() => chrome.tabs.remove(id));
  };
  chrome.tabs.onUpdated.addListener(h);
});

async function up({ b64: x, mime: capturedMime, meta }) {
  const fd = new FormData();
  const mime = capturedMime === 'image/jpeg' ? 'image/jpeg' : 'application/pdf';
  const extension = mime === 'image/jpeg' ? 'jpg' : 'pdf';
  fd.append('file', await (await fetch(`data:${mime};base64,${x}`)).blob(), `doc.${extension}`);
  fd.append('meta', JSON.stringify(meta));
  const r = await fetch(API + '/verify-doc', { method: 'POST', body: fd, headers: H });
  if (!r.ok) throw new Error('backend ' + r.status);
  return r.json();
}
async function poll(id) {
  const r = await fetch(`${API}/jobs/${id}`, { headers: H });
  if (r.status === 202) return { job_id: id, stage: (await r.json().catch(() => ({}))).stage };
  if (!r.ok) throw new Error('backend ' + r.status);
  return r.json();
}

chrome.runtime.onMessage.addListener((m, s, ok) => {
  if (m.t === 'pdf') chrome.tabs.sendMessage(s.tab.id, m);
  else if (m.t === 'watch') {
    const id = s.tab.id; watch = id;
    setTimeout(() => watch === id && (watch = null), 20000);
    ok({ watching: true });
  }
  else if (m.t === 'fetch') { grab(m.url).then(ok, e => ok({ err: String(e) })); return true; }
  else if (m.t === 'upload') { up(m).then(ok, e => ok({ err: String(e) })); return true; }
  else if (m.t === 'health') { fetch(API + '/health').then(r => r.json()).then(j => ok({ ...j, ok: true }), () => ok({ ok: false })); return true; }
  else if (m.t === 'poll') { poll(m.id).then(ok, e => ok({ err: String(e) })); return true; }
});
